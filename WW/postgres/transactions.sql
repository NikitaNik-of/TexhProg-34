-- ============================================================
-- Транзакция 1. Запись студента на курс.
-- Если любая из команд ниже упадёт с ошибкой, СУБД откатит всё.
-- ============================================================

BEGIN;

-- Шаг 1. Проверяем, нет ли уже записи (защита от дубликата).
SELECT COUNT(*) FROM enrollments 
WHERE student_id = 1 AND course_id = 4;

-- Шаг 2. Добавляем запись.
INSERT INTO enrollments (student_id, course_id, enrolled_at, status, progress_percent)
VALUES (1, 4, '2026-10-01', 'active', 0);

-- Шаг 3. Фиксируем изменения.
COMMIT;

-- ============================================================
-- Транзакция 2. Сложная бизнес-операция.
-- ============================================================

BEGIN;

UPDATE enrollments 
SET status = 'completed', progress_percent = 100
WHERE enrollment_id = 1;

COMMIT;